"""Builds the SQL seed files from database/seed/movies.json.

Run from the project root:   python tools/build_sql.py

Writes:
  database/seed/02_movies.sql   - INSERTs for every movie in movies.json
  database/setup_all.sql        - schema + functions + all seeds in one file
                                  (paste this into the Neon SQL Editor)
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DB = ROOT / "database"


def lit(v):
    if v is None:
        return "NULL"
    if isinstance(v, (int, float)):
        return str(v)
    if isinstance(v, list):
        return "ARRAY[" + ", ".join(lit(x) for x in v) + "]::text[]" if v else "'{}'::text[]"
    return "'" + str(v).replace("'", "''") + "'"


def movies_sql():
    movies = json.loads((DB / "seed" / "movies.json").read_text(encoding="utf-8"))
    cols = ["slug", "title", "tagline", "synopsis", "genres", "language", "certificate",
            "duration_min", "release_date", "rating", "director", "cast_members", "formats",
            "status", "poster_url"]
    rows = []
    for m in movies:
        vals = [m["slug"], m["title"], m["tagline"], m["synopsis"], m["genres"], m["language"],
                m["certificate"], m["duration_min"], m["release_date"], m["rating"], m["director"],
                m["cast"], m["formats"], m["status"], m["poster"]]
        rows.append("    (" + ", ".join(lit(v) for v in vals) + ")")
    updates = ", ".join(f"{c} = EXCLUDED.{c}" for c in cols if c != "slug")
    return (
        "-- Generated by tools/build_sql.py from movies.json. Do not edit by hand.\n"
        f"INSERT INTO movies ({', '.join(cols)}) VALUES\n" + ",\n".join(rows) +
        f"\nON CONFLICT (slug) DO UPDATE SET {updates};\n"
    )


def main():
    (DB / "seed" / "02_movies.sql").write_text(movies_sql(), encoding="utf-8")
    parts = ["schema.sql", "functions.sql", "seed/01_reference.sql", "seed/02_movies.sql",
             "seed/03_venues.sql", "seed/04_shows.sql"]
    combined = "-- FlixBooking: full database setup (generated by tools/build_sql.py)\n\n"
    for p in parts:
        combined += f"\n-- ===== {p} =====\n" + (DB / p).read_text(encoding="utf-8") + "\n"
    (DB / "setup_all.sql").write_text(combined, encoding="utf-8")
    print("wrote database/seed/02_movies.sql and database/setup_all.sql")


if __name__ == "__main__":
    main()
